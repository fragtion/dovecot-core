#!/usr/bin/env perl
# Embed the web UI files given as arguments into a C source file.
use strict;
use warnings;
use File::Basename;

my %types = (
	"html" => "text/html; charset=utf-8",
	"js" => "text/javascript; charset=utf-8",
	"css" => "text/css; charset=utf-8",
	"svg" => "image/svg+xml",
);

print "/* Generated by mesh-ui-gen.pl - do not edit */\n\n";
print "#include \"lib.h\"\n#include \"mesh-ui.h\"\n\n";
my @entries;
my $n = 0;
foreach my $path (@ARGV) {
	my $name = basename($path);
	my ($ext) = $name =~ /\.([^.]+)$/;
	my $type = $types{$ext // ""} // "application/octet-stream";
	open(my $fh, "<:raw", $path) or die "open($path): $!";
	local $/;
	my $data = <$fh>;
	close($fh);
	print "static const unsigned char mesh_ui_file$n\[\] = {";
	my $i = 0;
	foreach my $byte (unpack("C*", $data)) {
		print "\n\t" if $i++ % 16 == 0;
		printf "0x%02x,", $byte;
	}
	print "\n\t0\n};\n";
	push @entries, "\t{ \"$name\", \"$type\", mesh_ui_file$n, ".length($data)." },\n";
	$n++;
}
print "\nconst struct mesh_ui_file mesh_ui_files[] = {\n";
print @entries;
print "\t{ NULL, NULL, NULL, 0 }\n};\n";
